// Builds js/i18n/es-scripture.js: the verses of the Reina-Valera (1909, public domain) that the game quotes.
// usage: node tools/build-es-scripture.mjs <SpaRV.json> [verses.json]
//   SpaRV.json  from https://github.com/scrollmapper/bible_databases (formats/json/SpaRV.json)
//   verses.json list of "Acts 9:5" style references (defaults to tools/verses-needed.json)
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
const here = dirname(fileURLToPath(import.meta.url));
const src = JSON.parse(readFileSync(process.argv[2], 'utf8'));
const need = JSON.parse(readFileSync(process.argv[3] || join(here, 'verses-needed.json'), 'utf8'));
const roman = { 1: 'I', 2: 'II', 3: 'III' };
// The source prints the opening word(s) of some verses in capitals (a drop-cap convention): "VARONES hermanos", "Y DESPUÉS que".
// Restore ordinary capitalisation there; every other word is untouched.
const dropCap = (t) => t.replace(/^(Y )?([A-ZÁÉÍÓÚÑ]{2,})(?=[\s,.;:])/, (_, y, w) => { const low = w.toLowerCase(), cap = low[0].toUpperCase() + low.slice(1); return y ? y + (w === 'SAULO' ? cap : low) : cap; });
const out = {}, missing = [];
for (const ref of need) {
  const m = ref.match(/^(?:(\d) )?([A-Za-z]+) (\d+):(\d+)$/), name = (m[1] ? roman[m[1]] + ' ' : '') + m[2];
  const b = src.books.find(x => x.name === name), v = b && b.chapters[+m[3] - 1] && b.chapters[+m[3] - 1].verses.find(x => x.verse === +m[4]);
  if (v) out[ref] = dropCap(v.text.replace(/\s+/g, ' ').trim()); else missing.push(ref);
}
writeFileSync(join(here, '../js/i18n/es-scripture.js'), `// La Santa Biblia, Reina-Valera (1909) — public domain. Generated by tools/build-es-scripture.mjs; do not edit.\n// (Only change from the source: the drop-cap capitals that open some verses are written normally.)\nexport const RV = ${JSON.stringify(out, null, 1)};\n`);
console.log(Object.keys(out).length, 'verses written; missing:', missing);
